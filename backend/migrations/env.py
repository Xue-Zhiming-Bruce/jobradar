"""Alembic's environment: the revisions, and the one database they run against.

The URL comes from `app.db.database_url()` and from nowhere else, so `DATABASE_URL`
stays the only connection input and this file holds no credential. The engine is
the app's own `app.db.get_engine()`, so a SQLite connection created here carries
the pragmas `init_db()`'s connections carry, and the URL's scheme is checked by
the app's own gate rather than by SQLAlchemy's dialect loading.

`render_as_batch` is True for SQLite and for no other engine: the local
`backend/data/jobradar.db` is the database that already exists here, and SQLite
cannot express every `ALTER` without batch mode, which rebuilds the table and
copies the rows across. PostgreSQL alters in place and needs none of it.

`target_metadata` is `app.models.Base.metadata`, so autogenerate compares the
models with the database, and `tests/test_migrations.py` is what holds the two to
each other; the models stay the only place the schema is declared.

An autogenerated revision that holds no operation is discarded rather than
written, so running `revision --autogenerate` against a database already at
`head` leaves the history as it was instead of adding an empty file. A model
change autogenerate cannot express -- a changed CHECK constraint, a re-typed
column -- therefore leaves no file to edit: that revision is written by hand
with `alembic revision -m "<message>"`, as the README's schema section says.

Nothing here prints the URL or the credential in it: `fileConfig` reads only this
repository's `alembic.ini`, and no message built here names the database.
"""

import logging.config
from collections.abc import Sequence

from alembic import context
from alembic.operations.ops import MigrationScript
from alembic.runtime.migration import MigrationContext

from app import db
from app.models import Base

config = context.config

if config.config_file_name is not None:
    logging.config.fileConfig(config.config_file_name, disable_existing_loggers=False)

target_metadata = Base.metadata


def discard_an_empty_revision(
    migration_context: MigrationContext,
    revision: str | Sequence[str] | None,
    directives: list[MigrationScript],
) -> None:
    """Leave the history alone when autogenerate compared the database and found nothing."""
    if directives and not directives[0].upgrade_ops.is_empty():
        return
    del directives[:]


def run_migrations_online() -> None:
    """Connect through the app's own engine and apply the revisions on it.

    `db.get_engine()` is the engine `db.database_url()` builds, so the URL has one
    source, the scheme gate applies to it, and a SQLite connection opened here
    carries the same pragmas `init_db()`'s connections carry. It is also the one
    object the suite's `engine` fixture holds, so alembic's connections are the
    ones the fixture's leak check counts.
    """
    with db.get_engine().connect() as connection:
        context.configure(
            connection=connection,
            target_metadata=target_metadata,
            render_as_batch=connection.dialect.name == "sqlite",
            process_revision_directives=discard_an_empty_revision,
        )
        with context.begin_transaction():
            context.run_migrations()


run_migrations_online()
